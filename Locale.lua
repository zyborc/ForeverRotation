-- ForeverRotation – Sprachen.
--
-- Die Texte im Code sind deutsch und dienen als Schlüssel: L["Anzeige"].
--   * deutscher Client (deDE): Schlüssel = Text, nichts zu tun
--   * alle anderen Sprachen: englische Übersetzung unten
--   * fehlt eine Übersetzung, erscheint der deutsche Text (nie ein Fehler)
-- Zaubernamen werden NICHT hier übersetzt, sondern über ihre Zauber-ID vom Spiel
-- selbst (ns:SpellName). In Texten steht dafür ein Platzhalter: {Seal of Command}.
--
-- Weitere Sprache hinzufügen: unten einen Block `if LOCALE == "frFR" then ... end`
-- mit denselben Schlüsseln anlegen.

local _, ns = ...

local LOCALE = GetLocale and GetLocale() or "enUS"
ns.locale = LOCALE

local L = setmetatable({}, { __index = function(_, key) return key end })
ns.L = L

local function add(list)
    for key, text in pairs(list) do rawset(L, key, text) end
end

if LOCALE == "deDE" then return end

